import assert from 'node:assert/strict';
import { extractWorkspaceModalLayer } from './workspace-layer-source.mjs';
const base = 'http://127.0.0.1:4185';
const local = extractWorkspaceModalLayer(process.cwd());
const provenance = await (await fetch(base + '/__qa/workspace-layer-source')).json();
assert.equal(provenance.sha256, local.provenance.sha256);
assert.ok(local.source.includes('alertdialog'), 'Current real hook must include alertdialog');
const nested = await fetch(base + '/@fs' + process.cwd() + '/artifacts/qa/s02-transfer-guard/harness/NestedWorkspaceFixture.tsx');
assert.equal(nested.status, 200);
assert.match(await nested.text(), /__x00__virtual:s02-workspace-modal-layer/);
const virtual = await fetch(base + '/@id/__x00__virtual:s02-workspace-modal-layer');
assert.equal(virtual.status, 200);
const code = await virtual.text();
assert.match(code, /function useWorkspaceModalLayer/);
assert.ok(code.includes(local.provenance.sha256));
assert.ok(code.includes('alertdialog'));
const preview = await fetch(base + '/@fs' + process.cwd() + '/artifacts/qa/s02-transfer-guard/harness/preview.tsx');
assert.equal(preview.status, 200);
const previewCode = await preview.text();
assert.match(previewCode, /NestedWorkspaceFixture/);
assert.match(previewCode, /aria-disabled/);
const health = await (await fetch(base + '/__qa/health')).json();
assert.ok(health.preservedQa);
console.log(JSON.stringify({ passed: 'Original hook source/hash + Vite virtual module + nested fixture transform + launch focus preserved + prior QA retained', source: provenance, counts: health.counts }));

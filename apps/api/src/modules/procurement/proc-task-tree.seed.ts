export const INITIAL_PROC_TASK_TREE: ProcTaskTreeSeedRoot[] = (() => {
  const roots = new Map<string, ProcTaskTreeSeedChild[]>();
  for (const line of PROC_TASK_TREE_CATALOG.trim().split('\n')) {
    const [category, code, name, spec = ''] = line.split('|').map((value) => value.trim());
    if (!category || !name) continue;
    const children = roots.get(category) ?? [];
    children.push({ name, code, spec });
    roots.set(category, children);
  }
  return Array.from(roots, ([name, children]) => ({ name, children }));
})();
